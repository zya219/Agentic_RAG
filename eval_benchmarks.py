#!/usr/bin/env python3
"""Minimal benchmark evaluation for thesis baselines.

Supported baselines:
- hiprag: always retrieval-style agent prompt
- decision_aware: question-level retrieval decision (retrieve vs direct)
- token_level: same inference path, for token-level-trained checkpoint comparison
- react: load results generated by baseline_react.py
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from typing import Any

from openai import OpenAI
import transformers
from tqdm import tqdm

from inference import inference_vllm_single, decide_retrieval
from prompt import AGENT_PROMPT_V2_SHORT, DIRECT_PROMPT
from reward import cover_exact_match
from utils import extract_str_between, load_jsonl, write_jsonl


def _extract_answer_text(result_text: str) -> str:
    answers = extract_str_between(result_text, "<answer>", "</answer>")
    return answers[-1].strip() if answers else ""


def _search_count(result_text: str) -> int:
    return len(extract_str_between(result_text, "<search>", "</search>"))


def _summarize(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in rows:
        grouped[r.get("data_source", "unknown")].append(r)

    summary = []
    for ds, items in grouped.items():
        n = len(items)
        em = sum(1 for x in items if x.get("is_correct", False)) / max(n, 1)
        avg_search = sum(x.get("search_count", 0) for x in items) / max(n, 1)

        over = sum(1 for x in items if x.get("search_eval") == "oversearch")
        under = sum(1 for x in items if x.get("search_eval") == "undersearch")

        summary.append(
            {
                "data_source": ds,
                "count": n,
                "em": round(em, 4),
                "avg_search_count": round(avg_search, 4),
                "oversearch_count": over,
                "undersearch_count": under,
            }
        )

    summary = sorted(summary, key=lambda x: x["data_source"])

    # overall row
    total = len(rows)
    summary.append(
        {
            "data_source": "ALL",
            "count": total,
            "em": round(sum(1 for x in rows if x.get("is_correct", False)) / max(total, 1), 4),
            "avg_search_count": round(sum(x.get("search_count", 0) for x in rows) / max(total, 1), 4),
            "oversearch_count": sum(1 for x in rows if x.get("search_eval") == "oversearch"),
            "undersearch_count": sum(1 for x in rows if x.get("search_eval") == "undersearch"),
        }
    )
    return summary


def _print_summary_table(summary: list[dict[str, Any]]) -> None:
    print("\n=== Summary ===")
    print("data_source\tcount\tem\tavg_search\toversearch\tundersearch")
    for row in summary:
        print(
            f"{row['data_source']}\t{row['count']}\t{row['em']}\t"
            f"{row['avg_search_count']}\t{row['oversearch_count']}\t{row['undersearch_count']}"
        )


def run_generation_eval(args: argparse.Namespace) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    data = load_jsonl(args.input_jsonl)
    client = OpenAI(api_key=args.api_key, base_url=args.base_url)
    tokenizer = transformers.AutoTokenizer.from_pretrained(args.tokenizer_id or args.model_id)

    rows = []
    for ex in tqdm(data):
        question = ex["question"]

        if args.baseline == "hiprag":
            result = inference_vllm_single(question, client, args.model_id, AGENT_PROMPT_V2_SHORT, tokenizer)
            decision = True
        elif args.baseline == "decision_aware":
            decision = decide_retrieval(question)
            prompt = AGENT_PROMPT_V2_SHORT if decision else DIRECT_PROMPT
            result = inference_vllm_single(question, client, args.model_id, prompt, tokenizer)
        elif args.baseline == "token_level":
            result = inference_vllm_single(question, client, args.model_id, AGENT_PROMPT_V2_SHORT, tokenizer)
            decision = True
        else:
            raise ValueError(f"Unsupported generation baseline: {args.baseline}")

        final_answer = _extract_answer_text(result)
        golden = ex.get("golden_answers", ex.get("answer", ""))
        is_correct = cover_exact_match(final_answer, golden)

        rows.append(
            {
                **ex,
                "baseline": args.baseline,
                "decision": decision,
                "result": result,
                "final_answer": final_answer,
                "is_correct": bool(is_correct),
                "search_count": _search_count(result),
                # optional fields if upstream analysis wrote them
                "search_eval": ex.get("search_eval"),
            }
        )

    summary = _summarize(rows)
    return rows, summary


def run_result_eval(args: argparse.Namespace) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    rows = load_jsonl(args.input_jsonl)
    for r in rows:
        if "is_correct" not in r:
            answer = r.get("final_answer") or _extract_answer_text(r.get("result", ""))
            golden = r.get("golden_answers", r.get("answer", ""))
            r["is_correct"] = bool(cover_exact_match(answer, golden))
        if "search_count" not in r:
            r["search_count"] = _search_count(r.get("result", ""))
    return rows, _summarize(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description="Minimal benchmark evaluator for thesis baselines.")
    parser.add_argument("--baseline", choices=["hiprag", "decision_aware", "token_level", "react"], required=True)
    parser.add_argument("--input_jsonl", required=True, help="Benchmark jsonl or prediction jsonl.")
    parser.add_argument("--output_jsonl", required=True)
    parser.add_argument("--summary_jsonl", required=True)

    parser.add_argument("--base_url", default="http://localhost:8001/v1")
    parser.add_argument("--api_key", default="EMPTY")
    parser.add_argument("--model_id", default=None)
    parser.add_argument("--tokenizer_id", default=None, help="Optional tokenizer path/id. Defaults to --model_id.")

    args = parser.parse_args()

    if args.baseline == "react":
        rows, summary = run_result_eval(args)
    else:
        if not args.model_id:
            raise ValueError("--model_id is required for hiprag/decision_aware/token_level")
        rows, summary = run_generation_eval(args)

    write_jsonl(rows, args.output_jsonl)
    write_jsonl(summary, args.summary_jsonl)
    _print_summary_table(summary)
    print(f"\nSaved predictions to: {args.output_jsonl}")
    print(f"Saved summary to: {args.summary_jsonl}")


if __name__ == "__main__":
    main()
